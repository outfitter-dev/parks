/**
 * Writes packages/parks/src/themes/outfitter.css from the default preset in
 * packages/parks/src/lib/theme.ts.
 *
 *   bun scripts/ui-theme.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { compileTheme, defaultTheme } from "../packages/parks/src/lib/theme";

export const themePath = join(import.meta.dirname, "../packages/parks/src/themes/outfitter.css");

export function renderDefaultTheme(): string {
  return `/* Generated by scripts/ui-theme.ts from the outfitter preset in src/lib/theme.ts. Do not edit. */\n${compileTheme(defaultTheme)}\n`;
}

if (import.meta.main) {
  writeFileSync(themePath, renderDefaultTheme());
  console.log(`wrote ${themePath}`);
}

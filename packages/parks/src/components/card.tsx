import * as React from "react"
import { cn } from "#lib/utils"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card frame flex flex-col gap-(--frame-space) overflow-hidden bg-card py-(--frame-space) text-sm text-card-foreground shadow-(--shadow-frame) ring-1 ring-foreground/10 has-data-[slot=card-footer]:pb-0 has-[>img:first-child]:pt-0 data-[size=sm]:[--frame-pad:calc(var(--pad)*0.75)] data-[size=sm]:has-data-[slot=card-footer]:pb-0 *:[img:first-child]:rounded-t-frame *:[img:last-child]:rounded-b-frame",
        className
      )}
      {...props}
    />
  )
}

